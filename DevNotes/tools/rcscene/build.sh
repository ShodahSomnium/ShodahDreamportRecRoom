#!/bin/bash
# Builds rcscene (dotnet SDK 8). Gt.cs's Plates class (gtscene's exact-rectangle code) is taken out of ../gtscene/Gt.cs
# at build time, unchanged, so both tools share one copy of it. Output: out/bin/rcscene.dll
set -u
C="$(cd "$(dirname "$0")" && pwd)"
mkdir -p "$C/out"
{ echo "// generated by build.sh from ../gtscene/Gt.cs (class Plates, unchanged) - do not edit"
  echo "using System; using System.Linq; using System.Collections.Generic; using System.Globalization;"
  awk '/^static class Plates \{/ { on = 1 } /^static class GtPrep \{/ { on = 0 } on' "$C/../gtscene/Gt.cs"; } > "$C/out/Plates.g.cs"
cd "$C" && dotnet build -c Release -o "$C/out/bin" -v q -nologo 2>&1 | grep -E "error|Warn|warn" | grep -v "warning CS" | head -30
ls -la "$C/out/bin/rcscene.dll" | awk '{print $5, $9}'
