// Writes Places/RecCenter/RrRecCenterDressData.cs from out/data/rc_platecol.tsv: per level material a small palette
// (k-means on the plates' measured colours, area weighted) and, per plate, its centre tokens -> palette index.
// Numbers only (positions as the layout prints them, colours). Usage: node gen_dressdata.js <tsv> <out.cs>
const fs = require('fs');
const [tsv, out] = process.argv.slice(2);
const MATS = { RecCenter_CafeAssets_Mat: 12, Couch_Minimalist_Brown_Instanced_Mat: 4, RecCenter_Marquee_Mat: 6, Goblet_Clock_Mat: 3,
  LockerFountainStageLight_mat: 4, Quest_Poster_Case_Mat: 6, RecCenter_ProjectionScreen_Mat: 3 };
const rows = {};
for (const l of fs.readFileSync(tsv, 'utf8').split('\n')) {
  if (!l || l[0] === '#') continue; const p = l.split('\t'); const mat = p[0]; if (!(mat in MATS) || p[4] === '-') continue;
  const e = p[3].split(',').map(Number); const c = p[4].split(' ').map(Number);
  (rows[mat] = rows[mat] || []).push({ pos: p[1], c, w: Math.max(1e-4, 4 * e[0] * e[1]) });
}
const d2 = (a, b) => (a[0] - b[0]) ** 2 + (a[1] - b[1]) ** 2 + (a[2] - b[2]) ** 2;
function kmeans(pts, k) {
  // farthest-point seeding (area weighted first pick), then Lloyd
  const cs = [pts.reduce((a, b) => (b.w > a.w ? b : a)).c.slice()];
  while (cs.length < k) {
    let best = null, bd = -1; for (const p of pts) { const d = Math.min(...cs.map(c => d2(c, p.c))); if (d > bd) { bd = d; best = p; } }
    if (bd < 0.0016) break; cs.push(best.c.slice());
  }
  for (let it = 0; it < 30; it++) {
    const s = cs.map(() => [0, 0, 0, 0]);
    for (const p of pts) { let bi = 0; for (let i = 1; i < cs.length; i++) if (d2(cs[i], p.c) < d2(cs[bi], p.c)) bi = i; p.k = bi; const ww = Math.sqrt(p.w); s[bi][0] += p.c[0] * ww; s[bi][1] += p.c[1] * ww; s[bi][2] += p.c[2] * ww; s[bi][3] += ww; }
    for (let i = 0; i < cs.length; i++) if (s[i][3] > 0) cs[i] = [s[i][0] / s[i][3], s[i][1] / s[i][3], s[i][2] / s[i][3]];
  }
  for (const p of pts) { let bi = 0; for (let i = 1; i < cs.length; i++) if (d2(cs[i], p.c) < d2(cs[bi], p.c)) bi = i; p.k = bi; }
  return cs;
}
const f3 = x => (Math.round(x * 1000) / 1000).toString();
let cs = `// GENERATED by DevNotes/tools/rcdress/gen_dressdata.js from DevNotes/tools/rcdress/out/data/rc_platecol.tsv (rcdress platecol on
// Android level 7 and Layouts/RecCenter_Builtin). Do not edit by hand. Numbers only: per level material a palette of the colours
// the level shows on its plates (its own UVs on its own texture, measured; no texture, UV or vertex data is here) and, per
// plate, the plate's centre exactly as the layout prints it -> its palette entry.
namespace SomniumSpace.Worlds.RecRoomDreamport.Places.RecCenter
{
    internal static class RrRecCenterDressData
    {
        /// <summary>The level materials whose plates are recoloured, in the order of <see cref="Palettes"/> and <see cref="Plates"/>.</summary>
        public static readonly string[] Materials =
        {
`;
const mats = Object.keys(MATS).filter(m => rows[m]);
const pals = [], tabs = [], stats = [];
for (const m of mats) {
  const pts = rows[m]; const pal = kmeans(pts, MATS[m]);
  const seen = new Map(); let dup = 0;
  for (const p of pts) { if (seen.has(p.pos)) { dup++; continue; } seen.set(p.pos, p.k); }
  const area = pal.map(() => 0); for (const p of pts) area[p.k] += p.w;
  pals.push(pal); tabs.push([...seen.entries()].map(([pos, k]) => pos.replace(/ /g, ',') + ',' + k.toString(36)).join(';'));
  stats.push(`${m}: ${pts.length} plates (${seen.size} centres), palette ` + pal.map((c, i) => `${c.map(f3).join(',')} (${area[i].toFixed(2)} m2)`).join(' | '));
}
cs += mats.map(m => `            "${m}"`).join(',\n') + '\n        };\n\n';
cs += `        /// <summary>Per material: r,g,b triples (0..1, the texture's stored sRGB x the material colour), the measured plate colours' cluster means.</summary>
        public static readonly float[][] Palettes =
        {
` + pals.map(p => '            new[] { ' + p.map(c => c.map(x => f3(x) + 'f').join(', ')).join(',  ') + ' }').join(',\n') + '\n        };\n\n';
cs += `        /// <summary>Per material: "x,y,z,k;..." - a plate centre as the layout prints it and its palette entry (base 36).</summary>
        public static readonly string[] Plates =
        {
` + tabs.map(t => '            "' + t + '"').join(',\n') + '\n        };\n    }\n}\n';
fs.writeFileSync(out, cs);
console.log(stats.join('\n'));
