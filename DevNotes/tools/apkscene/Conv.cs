static class Conv {
  public static void Stats(string work, string level) {
    var L = new Ld(work); var m = Model.Load(L, level);
    Console.WriteLine($"{level}: {m.Gos.Count} GOs, {m.Rend.Count} renderers ({m.Rend.Count(r => r.Lod1)} LOD1+), {m.Col.Count} colliders, {m.Lights.Count} lights, {m.Aud.Count} audio, {m.Terr.Count} terrains, {m.Mbs.Count} MBs");
    Console.WriteLine("tree use: " + string.Join(", ", L.TreeHow.Select(kv => kv.Key + "=" + kv.Value)) + "; no tree: " + string.Join(",", L.NoTree.Select(kv => ClassNames.Of(kv.Key) + "=" + kv.Value)) + "; bad: " + string.Join(",", L.BadRead.Select(kv => ClassNames.Of(kv.Key) + "=" + kv.Value)));
    foreach (var t in m.Terr) Console.WriteLine($"terrain {t.Name} res {t.Res} scale {t.Scale} mat {t.Mat} layers {string.Join(",", t.Layers.Select(x => x.layer + ":" + x.tex))} col {t.Collider} {t.Note} at {m.GoW(t.Go).p}");
    Console.WriteLine("scripts: " + string.Join(", ", m.Mbs.GroupBy(x => x.Script).OrderByDescending(g => g.Count()).Take(80).Select(g => g.Key + "=" + g.Count())));
    var mn = m.Rend.Where(r => r.Mesh != null).GroupBy(r => r.Mesh.Combined ? "COMBINED" : r.Mesh.Name).OrderByDescending(g => g.Count()).Take(40);
    Console.WriteLine("meshes: " + string.Join(", ", mn.Select(g => g.Key + "=" + g.Count())));
    var rs = m.RS; if (rs != null) Console.WriteLine("fog " + rs["m_Fog"] + " " + string.Join(",", ((double[])rs["m_FogColor"]).Select(Y.F)) + " mode " + rs["m_FogMode"] + " dens " + rs["m_FogDensity"] + " lin " + rs["m_LinearFogStart"] + "-" + rs["m_LinearFogEnd"] + " ambient " + string.Join(",", ((double[])rs["m_AmbientSkyColor"]).Select(Y.F)) + " mode " + rs["m_AmbientMode"]);
  }
  public static void Run(string work, string outDir, string level, string scene, string[] opt) {
    var sw = System.Diagnostics.Stopwatch.StartNew();
    Directory.CreateDirectory(outDir);
    var L = new Ld(work); var m = Model.Load(L, level); var ix = InstIdx.Load(work);
    string refPath = opt.FirstOrDefault(o => o.StartsWith("ref="))?.Substring(4);
    string scenePath = opt.FirstOrDefault(o => o.StartsWith("scene="))?.Substring(6);
    if (scenePath == null) { var sl = Scan.Scenes(L); int li = int.TryParse(level.Replace("level", ""), out int q) ? q : -1; scenePath = li >= 0 && li < sl.Count ? sl[li] : "?"; }
    var outPath = Path.Combine(outDir, scene + ".rrsk");
    var st = Emit.Write(m, ix, scene, outPath, $"Android build 2026-03-23 (APKPure XAPK) {level} = {scenePath}");
    var md = new StringBuilder();
    md.Append($"# {scene} ({level}, `{scenePath}`)\n\nGenerated by DevNotes/tools/apkscene from the user's Android build (data only). RRSK: `{scene}.rrsk`.\n\n");
    md.Append("| item | value |\n| --- | --- |\n");
    md.Append($"| GameObjects | {st.Gos} |\n| renderers (active, LOD0) | {st.Rend} (+{st.RendLod} LOD1+, {st.RendInactive} inactive/disabled, {st.RendInPrefab} inside P/G prefabs, {st.RendNoMesh} runtime meshes e.g. text) |\n");
    md.Append($"| install mesh match | {st.Matched} / {st.Rend - st.RendNoMesh} = {st.MatchPct:F1}% ({st.MatchedCI} by letter case) |\n| stand-ins (X) | {st.X} boxes (+{st.U} #U); big unmatched meshes: {st.XGround} as H ground grids, {st.XVox} as voxel-shell X sets |\n| material slots with an install name | {st.SlotsKnown} / {st.Slots} |\n");
    md.Append($"| colliders (C) | {st.C}: box {st.CBox}, sphere {st.CSph}, capsule {st.CCap}, mesh {st.CMesh}; meshes not in the install: {st.CMeshH} as H ground grids, {st.CMeshVox} as voxel-shell boxes ({st.CVoxBoxes} C boxes), {st.CMeshBox} as one bounds box ({st.CInPrefab} inside prefabs skipped) |\n| prefabs (P) | {st.P} (+{st.PInactive} inactive) |\n| markers (G) | {st.G}: {string.Join(", ", st.GKinds.OrderByDescending(x => x.Value).Select(x => x.Key + " " + x.Value))} |\n");
    md.Append($"| lights / audio | {st.L} / {st.A} ({st.AKnown} install clips) |\n| terrain (H) | {(st.Terrain ? "yes" : "no")} |\n\n");
    if (st.Notes.Count > 0) { md.Append("## Notes\n"); foreach (var n in st.Notes) md.Append("- ").Append(n).Append('\n'); md.Append('\n'); }
    string val = "";
    if (refPath != null && File.Exists(refPath)) {
      var mine = File.ReadLines(outPath).Where(l => l.StartsWith("G flag_base ")).Select(l => l.Split(' ')).Select(p => (p[2], new V3(double.Parse(p[3]), double.Parse(p[4]), double.Parse(p[5])), string.Join(" ", p.Skip(10)))).ToList();
      var theirs = File.ReadLines(refPath).Where(l => l.StartsWith("G flag_base ")).Select(l => l.Split(' ')).Select(p => new V3(double.Parse(p[3]), double.Parse(p[4]), double.Parse(p[5]))).ToList();
      md.Append($"## Frame check against `{Path.GetFileName(refPath)}`\n| ref flag base | nearest scene flag base | offset (m) |\n| --- | --- | --- |\n");
      double worst = 0;
      foreach (var t in theirs) {
        if (mine.Count == 0) { md.Append($"| {t} | none | - |\n"); worst = double.PositiveInfinity; continue; }
        var best = mine.OrderBy(x => (x.Item2 - t).Len()).First(); var d = (best.Item2 - t).Len(); worst = Math.Max(worst, d);
        md.Append($"| {t} | {best.Item2} {best.Item3} | {d:F3} |\n");
      }
      val = theirs.Count == 0 ? "no flag bases in ref" : double.IsInfinity(worst) ? "no scene flag bases" : $"max {worst:F3} m over {theirs.Count}";
      md.Append($"\nResult: {val} ({(worst <= 0.5 ? "PASS" : "FAIL")} at 0.5 m).\n\n");
      // weapon spots: nearest scene weapon for each ref weapon pickup
      var mw = File.ReadLines(outPath).Where(l => l.StartsWith("G weapon_pickup ")).Select(l => l.Split(' ')).Select(p => (p[2], new V3(double.Parse(p[3]), double.Parse(p[4]), double.Parse(p[5])))).ToList();
      var tw = File.ReadLines(refPath).Where(l => l.StartsWith("G weapon_pickup ")).Select(l => l.Split(' ')).Select(p => (p[2], new V3(double.Parse(p[3]), double.Parse(p[4]), double.Parse(p[5])))).ToList();
      if (tw.Count > 0 && mw.Count > 0) {
        var ds = tw.Select(t => mw.Min(x => (x.Item2 - t.Item2).Len())).OrderBy(x => x).ToList();
        md.Append($"Weapon pickups: ref {tw.Count}, scene {mw.Count} (all sets); ref->nearest scene weapon: median {ds[ds.Count / 2]:F2} m, {ds.Count(x => x < 0.5)} of {ds.Count} within 0.5 m.\n\n");
        val += $"; weapons {ds.Count(x => x < 0.5)}/{ds.Count} within 0.5 m";
      }
    }
    md.Append("## Unmatched meshes (top 40; X stand-ins)\n"); foreach (var kv in st.Unmatched.OrderByDescending(x => x.Value).Take(40)) md.Append($"- {kv.Key} x{kv.Value}\n");
    md.Append("\n## Unmatched materials (top 25)\n"); foreach (var kv in st.UnmatchedMat.OrderByDescending(x => x.Value).Take(25)) md.Append($"- {kv.Key} x{kv.Value}\n");
    md.Append("\n## Prefabs placed (P)\n"); foreach (var kv in st.PNames.OrderByDescending(x => x.Value).Take(40)) md.Append($"- {kv.Key} x{kv.Value}\n");
    if (st.Signs.Count > 0) { md.Append("\n## Sign texts (first 30)\n"); foreach (var s in st.Signs.Distinct().Take(30)) md.Append("- ").Append(s.Length > 100 ? s.Substring(0, 100) : s).Append('\n'); }
    File.WriteAllText(Path.Combine(outDir, scene + ".md"), md.ToString());
    var row = $"{level}\t{scene}\t{scenePath}\t{st.Rend - st.RendNoMesh}\t{st.Matched}\t{st.MatchPct:F1}\t{st.C}\t{st.CMesh}\t{st.CMeshH + st.CMeshVox}\t{st.CMeshBox}\t{(st.Terrain ? "yes" : "no")}\t{st.P}\t{st.G}\t{st.X}\t{val}\t{new FileInfo(outPath).Length / 1024}";
    var tsv = Path.Combine(outDir, "_converted.tsv"); var rows = File.Exists(tsv) ? File.ReadAllLines(tsv).Where(l => !l.StartsWith(level + "\t")).ToList() : new List<string>(); rows.Add(row); File.WriteAllLines(tsv, rows);
    Console.WriteLine($"{scene}: {row.Replace('\t', ' ')}  [{sw.Elapsed.TotalSeconds:F1} s]");
  }
}
static class Find {
  public static void Run(string work, string level, string scriptRe, string nameRe) {
    var L = new Ld(work); var m = Model.Load(L, level);
    var sre = new System.Text.RegularExpressions.Regex(scriptRe, System.Text.RegularExpressions.RegexOptions.IgnoreCase);
    var nre = new System.Text.RegularExpressions.Regex(nameRe, System.Text.RegularExpressions.RegexOptions.IgnoreCase);
    int n = 0;
    foreach (var g in m.Gos.Values) {
      var scr = m.Mbs.Where(x => x.Go == g.Id).Select(x => x.Script).ToList();
      if (!(scr.Any(s => sre.IsMatch(s)) && nre.IsMatch(m.PathOf(g.Id)))) continue;
      var w = m.GoW(g.Id);
      if (n++ < 400) Console.WriteLine($"{m.PathOf(g.Id)} | {w.p} | {w.r} | act={m.Active(g.Id)} | {string.Join(",", scr.Take(8))}");
    }
    Console.WriteLine(n + " matches");
    var comb = m.Rend.Count(r => r.Mesh != null && r.Mesh.Combined); Console.WriteLine("combined-mesh renderers: " + comb + " / " + m.Rend.Count + "; batched (SubCount>0): " + m.Rend.Count(r => r.SubCount > 0));
  }
}
static class MeshDbg {
  public static void Run(string work, string level, string name) {
    var L = new Ld(work); var m = Model.Load(L, level);
    foreach (var c in m.Col) { if (c.Mesh == null || c.Mesh.Name != name) continue;
      var f = L.File(c.Mesh.File); var o = f.ById[c.Mesh.Pid]; var d = L.Read(f, o);
      var dd = new Dictionary<string, object>(d); foreach (var k in d.Keys) if (k == "m_BindPose" || k == "m_Shapes") dd.Remove(k);
      Console.WriteLine(c.Mesh.File + " " + c.Mesh.Pid); Console.WriteLine(Tools.Js(dd, 4, 0)); break; }
  }
}
static class HCheck {
  public static void Run(string work, string level) {
    var L = new Ld(work); var m = Model.Load(L, level);
    foreach (var t in m.Terr) {
      if (t.H == null) continue; var w = m.GoW(t.Go);
      double H(double wx, double wz, bool zMajor) { int u = (int)Math.Round((wx - w.p.x) / t.Scale.x), v = (int)Math.Round((wz - w.p.z) / t.Scale.z); if (u < 0 || v < 0 || u >= t.Res || v >= t.Res) return double.NaN; return w.p.y + (zMajor ? t.H[v * t.Res + u] : t.H[u * t.Res + v]) / 32766.0 * t.Scale.y; }
      var sp = m.Mbs.Where(x => x.Script == "GamePlayerSpawnPoint" && m.Active(x.Go)).Select(x => m.GoW(x.Go).p).ToList();
      var a = sp.Select(p => p.y - H(p.x, p.z, true)).Where(d => !double.IsNaN(d)).OrderBy(Math.Abs).ToList(); var b = sp.Select(p => p.y - H(p.x, p.z, false)).Where(d => !double.IsNaN(d)).OrderBy(Math.Abs).ToList();
      Console.WriteLine($"{t.Name}: {sp.Count} spawns; spawn.y - terrain(z-major): median |d| {(a.Count > 0 ? Math.Abs(a[a.Count / 2]) : double.NaN):F3}, within 0.3 m {a.Count(d => Math.Abs(d) < 0.3)}/{a.Count}; x-major: median |d| {(b.Count > 0 ? Math.Abs(b[b.Count / 2]) : double.NaN):F3}, within 0.3 m {b.Count(d => Math.Abs(d) < 0.3)}/{b.Count}");
    }
  }
}
static class Scan {
  /// BuildSettings scene list from globalgamemanagers (base APK): level index -> scene path.
  public static List<string> Scenes(Ld L) {
    var res = new List<string>(); if (!L.D.Has("globalgamemanagers")) return res;
    var b = L.D.Get("globalgamemanagers"); var key = Encoding.ASCII.GetBytes(".unity");
    for (int i = 8; i + 8 < b.Length; i++) {
      int n = BitConverter.ToInt32(b, i); if (n < 8 || n > 300 || i + 4 + n > b.Length) continue;
      if (!(b[i + 4 + n - 6] == '.' && b[i + 4 + n - 5] == 'u' && b[i + 4 + n - 1] == 'y')) continue;
      int cnt = BitConverter.ToInt32(b, i - 4); if (cnt < 2 || cnt > 2000) continue;
      int p = i;
      for (int k = 0; k < cnt; k++) { int len = BitConverter.ToInt32(b, p); if (len < 0 || len > 400) { res.Clear(); break; } res.Add(Encoding.UTF8.GetString(b, p + 4, len)); p += 4 + ((len + 3) & ~3); }
      if (res.Count == cnt) return res; res.Clear();
    }
    return res;
  }
  public static void Run(string work, string outDir) {
    var L0 = new Ld(work); var scenes = Scenes(L0); var ix = InstIdx.Load(work);
    Console.WriteLine($"{scenes.Count} scenes in BuildSettings");
    var rows = new List<string>();
    for (int li = 0; li < Math.Max(scenes.Count, 114); li++) {
      var lv = "level" + li; var sp = li < scenes.Count ? scenes[li] : "?";
      try {
        var L = new Ld(work); if (L.File(lv) == null) { rows.Add($"{lv}\t{sp}\tmissing"); continue; }
        var m = Model.Load(L, lv);
        var act = m.Rend.Where(r => !r.Lod1 && r.En && m.Active(r.Go) && r.Mesh != null && !string.IsNullOrEmpty(r.Mesh.Name)).ToList();
        int match = act.Count(r => ix.Mesh.ContainsKey(r.Mesh.Name) || ix.MeshCI.ContainsKey(r.Mesh.Name));
        int cols = m.Col.Count(c => c.En && !c.Trig && m.Active(c.Go));
        var roots = m.Trs.Values.Where(t => t.Father == 0).Select(t => m.Name(t.Go)).Distinct().Take(8);
        var signs = m.Mbs.Where(x => x.Script.StartsWith("TMPro.TextMeshPro") && m.Active(x.Go) && x.D?.Str("m_text") is string s && s.Trim().Length > 2).Select(x => x.D.Str("m_text").Replace("\n", " ").Replace("\t", " ").Trim()).Distinct().Take(6);
        var gs = m.Mbs.Select(x => x.Script).Where(s => System.Text.RegularExpressions.Regex.IsMatch(s, "Spawn|Flag|Goal|Checkpoint|Game|Quest|Enemy|Boss|Door|Teleport|Ball|Paddle|Disc|Bowling|Charades|Soccer", System.Text.RegularExpressions.RegexOptions.IgnoreCase)).GroupBy(s => s).OrderByDescending(g => g.Count()).Take(6).Select(g => g.Key + "=" + g.Count());
        rows.Add($"{lv}\t{sp}\t{m.Gos.Count}\t{act.Count}\t{match}\t{(act.Count == 0 ? 0 : 100.0 * match / act.Count):F1}\t{cols}\t{(m.Terr.Any(t => t.H != null && m.Active(t.Go)) ? "yes" : "no")}\t{string.Join(", ", roots)}\t{string.Join(" / ", signs)}\t{string.Join(", ", gs)}");
        Console.WriteLine(rows[^1].Length > 200 ? rows[^1].Substring(0, 200) : rows[^1]);
      } catch (Exception e) { rows.Add($"{lv}\t{sp}\terror {e.Message}"); }
    }
    File.WriteAllLines(Path.Combine(outDir, "_levels.tsv"), rows);
  }
